-- ====================================================================
-- SUPABASE POSTGRESQL PRODUCTION SCHEMA & ROW LEVEL SECURITY (RLS)
-- Run this script inside Supabase Dashboard -> SQL Editor
-- ====================================================================

-- 1. Create TODOS Table
CREATE TABLE IF NOT EXISTS public.todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    title TEXT NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    time_spent INTEGER NOT NULL DEFAULT 0,
    description TEXT DEFAULT '',
    priority TEXT NOT NULL DEFAULT 'medium',
    deadline TEXT DEFAULT '',
    karma INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Indexes for high-performance sorting & filtering
CREATE INDEX IF NOT EXISTS idx_todos_user_id ON public.todos(user_id);
CREATE INDEX IF NOT EXISTS idx_todos_priority ON public.todos(priority);
CREATE INDEX IF NOT EXISTS idx_todos_deadline ON public.todos(deadline);

-- 2. Create CHECKLIST ITEMS Table (Sub-tasks)
CREATE TABLE IF NOT EXISTS public.checklist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    todo_id BIGINT NOT NULL REFERENCES public.todos(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_checklist_todo_id ON public.checklist_items(todo_id);

-- 3. Create POMODORO SESSIONS Table
CREATE TABLE IF NOT EXISTS public.pomodoro_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    todo_id BIGINT REFERENCES public.todos(id) ON DELETE SET NULL,
    duration_minutes INTEGER NOT NULL DEFAULT 25,
    completed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON public.pomodoro_sessions(user_id);

-- ====================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES (SECURITY-FIRST ISOLATION)
-- Ensures users can ONLY access & modify their own data
-- ====================================================================

-- Enable RLS on all tables
ALTER TABLE public.todos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.checklist_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pomodoro_sessions ENABLE ROW LEVEL SECURITY;

-- --------------------------------------------------------------------
-- Policies for TODOS
-- --------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view their own todos" ON public.todos;
CREATE POLICY "Users can view their own todos"
    ON public.todos FOR SELECT
    USING (auth.uid() = user_id OR user_id IS NULL);

DROP POLICY IF EXISTS "Users can insert their own todos" ON public.todos;
CREATE POLICY "Users can insert their own todos"
    ON public.todos FOR INSERT
    WITH CHECK (auth.uid() = user_id OR user_id IS NULL);

DROP POLICY IF EXISTS "Users can update their own todos" ON public.todos;
CREATE POLICY "Users can update their own todos"
    ON public.todos FOR UPDATE
    USING (auth.uid() = user_id OR user_id IS NULL);

DROP POLICY IF EXISTS "Users can delete their own todos" ON public.todos;
CREATE POLICY "Users can delete their own todos"
    ON public.todos FOR DELETE
    USING (auth.uid() = user_id OR user_id IS NULL);

-- --------------------------------------------------------------------
-- Policies for CHECKLIST ITEMS
-- --------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can manage checklist items of their todos" ON public.checklist_items;
CREATE POLICY "Users can manage checklist items of their todos"
    ON public.checklist_items FOR ALL
    USING (
        EXISTS (
            SELECT 1 FROM public.todos
            WHERE public.todos.id = public.checklist_items.todo_id
            AND (public.todos.user_id = auth.uid() OR public.todos.user_id IS NULL)
        )
    );

-- --------------------------------------------------------------------
-- Policies for POMODORO SESSIONS
-- --------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view their own pomodoro sessions" ON public.pomodoro_sessions;
CREATE POLICY "Users can view their own pomodoro sessions"
    ON public.pomodoro_sessions FOR SELECT
    USING (auth.uid() = user_id OR user_id IS NULL);

DROP POLICY IF EXISTS "Users can insert their own pomodoro sessions" ON public.pomodoro_sessions;
CREATE POLICY "Users can insert their own pomodoro sessions"
    ON public.pomodoro_sessions FOR INSERT
    WITH CHECK (auth.uid() = user_id OR user_id IS NULL);

DROP POLICY IF EXISTS "Users can update their own pomodoro sessions" ON public.pomodoro_sessions;
CREATE POLICY "Users can update their own pomodoro sessions"
    ON public.pomodoro_sessions FOR UPDATE
    USING (auth.uid() = user_id OR user_id IS NULL);

DROP POLICY IF EXISTS "Users can delete their own pomodoro sessions" ON public.pomodoro_sessions;
CREATE POLICY "Users can delete their own pomodoro sessions"
    ON public.pomodoro_sessions FOR DELETE
    USING (auth.uid() = user_id OR user_id IS NULL);
